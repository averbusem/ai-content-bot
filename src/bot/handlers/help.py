async def _send_help_menu(message: types.Message) -> None:
    await message.edit_text(
        "❓ <b>Помощь</b>\n\n"
        "Я бот для помощи НКО в создании контента для социальных сетей. "
        "Я помогу вам создавать посты, изображения, редактировать тексты и планировать публикации.\n\n"
        "<b>Если появилась непонятная ошибка — выберите в меню /start, чтобы перезапустить работу.</b>\n\n"
        "Выберите раздел, который хотите посмотреть:",
        reply_markup=help_menu_keyboard(),
    )


@router.callback_query(F.data == "main_menu:help")
async def help_handler(callback: types.CallbackQuery, state: FSMContext):
    await callback.answer()
    await _send_help_menu(callback.message)


@router.callback_query(F.data == "help:menu")
async def help_menu_callback(callback: types.CallbackQuery, state: FSMContext):
    await callback.answer()
    await _send_help_menu(callback.message)


@router.callback_query(F.data.startswith("help:section:"))
async def help_section_handler(callback: types.CallbackQuery, state: FSMContext):
    await callback.answer()
    section_key = callback.data.split(":")[-1]
    section = HELP_SECTIONS.get(section_key)
    if not section:
        return await callback.answer("Раздел не найден", show_alert=True)

    await callback.message.edit_text(
        f"❓ <b>Помощь — {section['title']}</b>\n\n{section['text']}",
        reply_markup=help_section_keyboard(),
    )
